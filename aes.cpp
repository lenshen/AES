//  轉成陣列 跟反轉 及 key 分割
void array_to_mat(unsigned char p[16], unsigned char state_mat[4][4]) {
    for(int i = 0; i < 4; i++)
        for(int j = 0; j < 4; j++)
            state_mat[j][i] = p[i * 4 + j];
}
void mat_to_array(unsigned char state_mat[4][4], unsigned char c[16]) {
    for(int i = 0; i < 4; i++)
        for(int j = 0; j < 4; j++)
            c[i * 4 + j] = state_mat[j][i];
}
void key32_to_key8(unsigned int key32, unsigned char* key8) {
    key8[0] = (key32 >> 24) & 0xFF; key8[1] = (key32 >> 16) & 0xFF;
    key8[2] = (key32 >> 8) & 0xFF;  key8[3] = key32 & 0xFF;
}
unsigned int key8_to_key32(unsigned char* key8) {
    return (key8[0] << 24) | (key8[1] << 16) | (key8[2] << 8) | key8[3];
}

// GF(2^8) 乘法 
unsigned char multi_finite_field(unsigned char a, unsigned char b) {
    unsigned char p = 0;
    for (int i = 0; i < 8; i++) {
        if (b & 1) p ^= a;
        bool hi = (a & 0x80);
        a <<= 1;
        if (hi) a ^= 0x1B;
        b >>= 1;
    }
    return p;
}

// 4 steps
void SubBytes(unsigned char state_mat[4][4]) {
    for(int i=0; i<4; i++) for(int j=0; j<4; j++) state_mat[i][j] = S[state_mat[i][j]];
}
void ShiftRows(unsigned char state_mat[4][4]) {
    unsigned char temp[4];
    for(int i=1; i<4; i++){
        for(int j=0; j<4; j++) temp[(4-i+j)%4] = state_mat[i][j];
        for(int j=0; j<4; j++) state_mat[i][j] = temp[j];
    }
}
void MixColumns(unsigned char state_mat[4][4]) {
    unsigned char temp[4];
    for (int c = 0; c < 4; c++) {
        for (int r = 0; r < 4; r++) temp[r] = state_mat[r][c];
        for (int r = 0; r < 4; r++) {
            state_mat[r][c] = multi_finite_field(positive_matrix[r][0], temp[0]) ^
                              multi_finite_field(positive_matrix[r][1], temp[1]) ^
                              multi_finite_field(positive_matrix[r][2], temp[2]) ^
                              multi_finite_field(positive_matrix[r][3], temp[3]);
        }
    }
}
void AddRoundKey(unsigned char state_mat[4][4], int cnt) {
    unsigned char key8[4];
    for (int c = 0; c < 4; c++) {
        key32_to_key8(W[cnt * 4 + c], key8);
        for (int r = 0; r < 4; r++) state_mat[r][c] ^= key8[r];
    }
}

// 4 steps in
void Inv_SubBytes(unsigned char state_mat[4][4]) {
    for(int i=0; i<4; i++) for(int j=0; j<4; j++) state_mat[i][j] = inv_S[state_mat[i][j]];
}
void Inv_ShiftRows(unsigned char state_mat[4][4]) {
    unsigned char temp[4];
    for(int i=1; i<4; i++){
        for(int j=0; j<4; j++) temp[(i+j)%4] = state_mat[i][j]; 
        for(int j=0; j<4; j++) state_mat[i][j] = temp[j];
    }
}
void Inv_MixColumns(unsigned char state_mat[4][4]) {
    unsigned char temp[4];
    for (int c = 0; c < 4; c++) {
        for (int r = 0; r < 4; r++) temp[r] = state_mat[r][c];
        for (int r = 0; r < 4; r++) {
            state_mat[r][c] = multi_finite_field(inv_positive_matrix[r][0], temp[0]) ^
                              multi_finite_field(inv_positive_matrix[r][1], temp[1]) ^
                              multi_finite_field(inv_positive_matrix[r][2], temp[2]) ^
                              multi_finite_field(inv_positive_matrix[r][3], temp[3]);
        }
    }
}

// 金鑰擴展
unsigned int T(unsigned int input, int cnt) {
    unsigned char key8[4];
    key32_to_key8(input, key8);
    unsigned char temp[4];
    for(int i=0; i<4; i++) temp[(3+i)%4] = key8[i];
    for(int i=0; i<4; i++) key8[i] = S[temp[i]];
    return key8_to_key32(key8) ^ rcon[cnt];
}
void KeyExpansion(unsigned char* init_key) {
    for (int i = 0; i < 4; i++) {
        unsigned char temp[4] = {init_key[i*4], init_key[i*4+1], init_key[i*4+2], init_key[i*4+3]};
        W[i] = key8_to_key32(temp);
    }
    for (int i = 4; i < 44; i++) {
        unsigned int temp = W[i - 1]; 
        if (i % 4 == 0) temp = T(temp, i / 4 - 1); 
        W[i] = W[i - 4] ^ temp;
    }
}

// 每一塊解法
void block_encryption() {
    unsigned char state_mat[4][4];
    array_to_mat(P128, state_mat);
    AddRoundKey(state_mat, 0);
    for (int round = 1; round < 10; round++) {
        SubBytes(state_mat); ShiftRows(state_mat); MixColumns(state_mat); AddRoundKey(state_mat, round);
    }
    SubBytes(state_mat); ShiftRows(state_mat); AddRoundKey(state_mat, 10);
    mat_to_array(state_mat, C128);
}

void block_decryption() {
    unsigned char state_mat[4][4];
    array_to_mat(C128, state_mat);
    AddRoundKey(state_mat, 10);
    for (int round = 9; round >= 1; round--) {
        Inv_ShiftRows(state_mat); Inv_SubBytes(state_mat); AddRoundKey(state_mat, round); Inv_MixColumns(state_mat);
    }
    Inv_ShiftRows(state_mat); Inv_SubBytes(state_mat); AddRoundKey(state_mat, 0);
    mat_to_array(state_mat, P128);
}


// CBC
vector<unsigned char> encrypt_CBC(string s) {
    vector<unsigned char> padded_data;
    for (int i = 0; i < s.length(); i++) padded_data.push_back((unsigned char)s[i]);
    
    // 填充計算
    int pad_len = 16 - (s.length() % 16);
    for (int i = 0; i < pad_len; i++) padded_data.push_back((unsigned char)pad_len);
    
    vector<unsigned char> final_ciphertext;
    unsigned char prev_cipher[16];
    for (int i = 0; i < 16; i++) prev_cipher[i] = IV[i];
    
    for (int offset = 0; offset < padded_data.size(); offset += 16) {
        for(int i = 0; i < 16; i++) {
            P128[i] = padded_data[offset + i] ^ prev_cipher[i]; // XOR 前一次的密文 (或 IV)
        }
        
        block_encryption(); // 
        
        for(int i = 0; i < 16; i++){
            final_ciphertext.push_back(C128[i]);
            prev_cipher[i] = C128[i]; // 更新 prev_cipher
        }
    }
    return final_ciphertext;
}

string decrypt_CBC(vector<unsigned char> cipher_result) {
    vector<unsigned char> padded_plaintext;
    unsigned char prev_cipher[16];
    for (int i = 0; i < 16; i++) prev_cipher[i] = IV[i];
    
    for (int offset = 0; offset < cipher_result.size(); offset += 16) {
        // 將 16 bytes 密文載入
        for (int i = 0; i < 16; i++) C128[i] = cipher_result[offset + i];
        
        block_decryption(); 
        
        for (int i = 0; i < 16; i++) {
            // 還原明文 = 解密輸出 XOR 前一次的密文 (或 IV)
            unsigned char original_char = P128[i] ^ prev_cipher[i];
            padded_plaintext.push_back(original_char);
            prev_cipher[i] = cipher_result[offset + i]; // 抓取原本的「密文」準備給下一塊用
        }
    }
    
    // 除掉 填充物
    int pad_len = padded_plaintext.back(); // 從最後一個byte 知道剩幾個空位
    int valid_len = padded_plaintext.size() - pad_len;
    
    string plaintext = "";
    for(int i = 0; i < valid_len; i++) {
        plaintext += (char)padded_plaintext[i];
    }
    
    return plaintext;
}